// Bundles marketing/playbooks/**.md into one TypeScript module, so the server can use them on Vercel
// without reading files at runtime. Run after updating the playbooks.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const root = "marketing/playbooks";
const files = [];
const walk = (d) => readdirSync(d).forEach((n) => {
  const p = join(d, n);
  if (statSync(p).isDirectory()) walk(p);
  else if (n.endsWith(".md") && n !== "README.md") files.push(p);
});
walk(root);
const entries = files.sort().map((p) => `  ${JSON.stringify(relative(root, p))}: ${JSON.stringify(readFileSync(p, "utf8"))},`);
writeFileSync("src/lib/marketing/playbooks.generated.ts",
  `// Generated by scripts/build-marketing-playbooks.mjs from marketing/playbooks (MIT, coreyhaines31/marketingskills). Do not edit.\nexport const PLAYBOOKS: Record<string, string> = {\n${entries.join("\n")}\n};\n`);
console.log(`bundled ${files.length} playbooks`);
